// Works out each jar item's artwork bounds (its alpha bounding box) from the
// image files, so the footer carousel doesn't have to scan the images in the
// browser (that scan was a visible cost as the footer came near).
// Run after changing an item image:  node scripts/item-bboxes.mjs
import sharp from "sharp";
import fs from "node:fs";

sharp.cache(false);
const manifest = fs.readFileSync("components/sections/Hero/items.manifest.ts", "utf8");
const srcs = [...new Set([...manifest.matchAll(/src:\s*"([^"]+)"/g)].map((m) => m[1]))];
const out = {};
for (const src of srcs) {
  const { data, info } = await sharp(fs.readFileSync("public" + decodeURI(src)))
    .ensureAlpha()
    .raw()
    .toBuffer({ resolveWithObject: true });
  const { width: w, height: h } = info;
  let x0 = w, y0 = h, x1 = -1, y1 = -1;
  for (let y = 0; y < h; y++)
    for (let x = 0; x < w; x++)
      if (data[(y * w + x) * 4 + 3] > 8) {
        if (x < x0) x0 = x;
        if (x > x1) x1 = x;
        if (y < y0) y0 = y;
        if (y > y1) y1 = y;
      }
  out[src] = x1 < 0
    ? { naturalWidth: w, naturalHeight: h, bboxX: 0, bboxY: 0, bboxW: w, bboxH: h }
    : { naturalWidth: w, naturalHeight: h, bboxX: x0, bboxY: y0, bboxW: x1 - x0 + 1, bboxH: y1 - y0 + 1 };
}
fs.writeFileSync(
  "lib/itemBBoxes.ts",
  `// Generated by scripts/item-bboxes.mjs: each jar item image's artwork bounds\n// (alpha bounding box), in the file's own pixels. Don't edit by hand; rerun\n// the script after changing an item image.\n\nexport const ITEM_BBOXES: Record<string, { naturalWidth: number; naturalHeight: number; bboxX: number; bboxY: number; bboxW: number; bboxH: number }> = ${JSON.stringify(out, null, 2)};\n`,
);
console.log(Object.keys(out).length, "items");
